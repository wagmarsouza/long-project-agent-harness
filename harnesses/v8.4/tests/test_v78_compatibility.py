"""Use the preserved actual V7.8 executor to produce a legacy project."""
import importlib.util
from pathlib import Path
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


old = load('compat_v78', ROOT / 'tests/fixtures/harness_v78.py')
new = load('compat_v79', ROOT / 'scripts/harness.py')


class CompatibilityTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='harness-legacy-')
        self.root = Path(self.temp.name)
        (self.root / 'result.txt').write_text('correct', encoding='utf-8')
        self.old = old.Harness(self.root)
        self.old.init({'objective': 'Keep legacy verified scope', 'mode': 'light', 'in_scope': ['result.txt'], 'out_of_scope': [],
                       'criteria': [{'id': 'C1', 'description': 'Exact result text',
                                     'argv': [sys.executable, '-c', "from pathlib import Path; assert Path('result.txt').read_text() == 'correct'"],
                                     'artifacts': ['result.txt']}]})
        review = self.old.review('legacy')['review']
        self.cid = self.old.start({'topic': 'legacy', 'task': 'verify-old', 'premise': 'exact text', 'residual': 'execute',
                                  'review_id': review['id'], 'criteria': ['C1'],
                                  'approach': {'method': 'exact check', 'inputs': 'result.txt', 'environment': 'local'}})['cycle']
        self.check = self.old.check(self.cid, 'C1')
        self.old.claim({'id': 'legacy-fact', 'topic': 'legacy', 'statement': 'The legacy local check passed',
                        'kind': 'fact', 'cycle': self.cid, 'criterion': 'C1'})
        self.old.close(self.cid, 'verified', 'Legacy acceptance passed')
        self.new = new.Harness(self.root)
        self.legacy_bytes = self.old.db.read_bytes()
        self.migration = self.new.migrate_sqlite()

    def tearDown(self):
        self.temp.cleanup()

    def test_explicit_migration_preserves_legacy_bytes_and_history(self):
        self.assertTrue(self.new.validate()['passed'])
        self.assertEqual(self.new.resume()['claims']['legacy-fact']['status'], 'verified')
        self.new.capsule(output='CAPSULE.json')
        self.assertTrue(self.new.capsule_status('CAPSULE.json')['fresh'])
        self.assertEqual(self.old.db.read_bytes(), self.legacy_bytes)
        self.assertEqual(self.migration['canonical_store'], '.harness/state.yaml')

    def test_new_scope_annotation_preserves_legacy_contract_and_cycle(self):
        before = self.old.resume()
        self.new.evidence_scope({'cycle': self.cid, 'check_id': self.check['id'], 'method': 'dynamic', 'environment': 'local',
                                 'verifies': ['The legacy declared text'], 'does_not_verify': ['Production'], 'untested': [], 'coverage': []})
        after = self.new.resume()
        self.assertEqual(before['mission_hash'], after['mission_hash'])
        self.assertEqual(before['recent_cycles'], after['recent_cycles'])
        self.assertEqual(before['claims'], after['claims'])
        self.assertTrue(self.new.validate()['passed'])

    def test_legacy_export_can_be_regenerated_without_overwriting_unrelated_files(self):
        self.old.export('REPORT.md')
        self.new.export('REPORT.md')
        self.assertTrue((self.root / 'REPORT.md').read_text(encoding='utf-8').startswith('# GENERATED BY HARNESS 8.0'))


if __name__ == '__main__':
    unittest.main()
